<?php

declare(strict_types=1);

/**
 * Regenerates .gitleaks.toml and .semgrepignore from secret-scan-allowlist.json, the single source of truth for intentional fixtures.
 *
 *   php scripts/secret-scan-sync.php          write both files
 *   php scripts/secret-scan-sync.php --check  exit 1 when either file is out of date (CI and tests/Unit/SecretScanTest.php)
 */

require_once __DIR__ . '/secret-scan.php';

/** @return array{gitleaks:string,semgrep:string} */
function secret_scan_render(string $allowlistFile): array
{
    $allow = secret_scan_load_allowlist($allowlistFile);
    $toml = "# Generated by scripts/secret-scan-sync.php from secret-scan-allowlist.json. Do not edit by hand.\n"
        . "# Every entry is an intentional, documented fixture; the reason is the description.\n"
        . "title = \"rivet-core\"\n\n[extend]\nuseDefault = true\n\n"
        . "[[allowlists]]\ndescription = \"Installed dependencies are not tracked content\"\npaths = ['''(^|/)vendor/''']\n";
    $ignore = "# Generated by scripts/secret-scan-sync.php from secret-scan-allowlist.json. Do not edit by hand.\n"
        . "# Test fixtures that must contain secret-looking values (each documented in secret-scan-allowlist.json).\n";
    foreach ($allow['rules'] as $r) {
        $re = '(^|/)' . substr(secret_scan_glob_to_regex($r["path"]), 2, -2);
        $re = str_replace('\/', '/', $re);
        $reason = str_replace(['\\', '"'], ['\\\\', '\\"'], (string) $r['reason']);
        $toml .= "\n[[allowlists]]\ndescription = \"{$reason}\"\npaths = ['''{$re}$''']\n";
        if (($r['semgrep'] ?? true) !== false) {
            $ignore .= "\n# " . $r['reason'] . "\n/" . $r['path'] . "\n";
        }
    }
    return ['gitleaks' => $toml, 'semgrep' => $ignore];
}

if (PHP_SAPI === 'cli' && isset($argv[0]) && realpath($argv[0]) === __FILE__) {
    $root = dirname(__DIR__);
    $out = secret_scan_render($root . '/secret-scan-allowlist.json');
    $files = ['.gitleaks.toml' => $out['gitleaks'], '.semgrepignore' => $out['semgrep']];
    $stale = 0;
    foreach ($files as $name => $content) {
        $path = $root . '/' . $name;
        if (in_array('--check', $argv, true)) {
            if (!is_file($path) || file_get_contents($path) !== $content) {
                fwrite(STDERR, "$name is out of date: run php scripts/secret-scan-sync.php\n");
                $stale++;
            }
        } else {
            file_put_contents($path, $content);
        }
    }
    exit($stale > 0 ? 1 : 0);
}
